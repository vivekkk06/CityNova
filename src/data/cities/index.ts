export function getAllCitiesSummary(): CitySummary[] {
  return Object.values(CITIES_DATA).map((city) => ({
    id: city.id,
    name: city.name,
    state: city.state,
    district: city.district,
    governingBodyName: city.governingBodyName,
  }));
}

export function getCityInfo(cityIdOrName?: string | null): CityInfo | null {
  if (!cityIdOrName) return null;
  const normalized = cityIdOrName.trim().toLowerCase();

  // Try direct ID match
  if (CITIES_DATA[normalized]) {
    return CITIES_DATA[normalized];
  }

  // Try case-insensitive name match
  const found = Object.values(CITIES_DATA).find(
    (c) => c.name.toLowerCase() === normalized || c.id.toLowerCase() === normalized
  );

  return found || null;
}

