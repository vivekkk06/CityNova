'use client';

import React from 'react';
import { CalendarDays, Clock3, MapPin } from 'lucide-react';
import { formatSlaTimeRemaining } from '@/lib/sla';

interface CommitmentCardProps {
  caseId: string;
  cityName: string;
  publicCommitmentDate: string | Date;
  slaDeadline: string | Date;
  urgency: string;
  status: string;
}

export default function CommitmentCard({ caseId, cityName, publicCommitmentDate, slaDeadline, urgency, status }: CommitmentCardProps) {
  const remaining = formatSlaTimeRemaining(slaDeadline);
  const createdAt = new Date(publicCommitmentDate);
  const target = new Date(slaDeadline);

  return (
    <section className="relative overflow-hidden rounded-2xl border-2 border-slate-200 bg-white p-6 shadow-md">
      <div className="tricolor-bar absolute inset-x-0 top-0 h-1.5" />
      <div className="mb-5 flex flex-wrap items-center justify-between gap-3 border-b border-slate-200 pb-4 pt-1">
        <div><p className="mb-1 text-[11px] font-bold uppercase tracking-wider text-slate-500">Public Grievance Docket</p><h2 className="font-mono text-xl font-extrabold tracking-tight text-slate-900">{caseId}</h2></div>
        <div className="flex gap-2"><span className="rounded-full border border-orange-200 bg-orange-50 px-3 py-1 text-xs font-bold text-orange-800">{urgency} priority</span><span className="rounded-full border border-blue-200 bg-blue-50 px-3 py-1 text-xs font-bold text-blue-800">{status.replace(/_/g, ' ')}</span></div>
      </div>
      <div className="grid grid-cols-1 gap-3 sm:grid-cols-3">
        <div className="rounded-xl border border-slate-200 bg-slate-50 p-3.5"><div className="mb-1 flex items-center gap-2 text-xs font-semibold text-slate-500"><MapPin className="h-3.5 w-3.5 text-blue-600" />City</div><p className="text-sm font-bold text-slate-900">{cityName}</p></div>
        <div className="rounded-xl border border-slate-200 bg-slate-50 p-3.5"><div className="mb-1 flex items-center gap-2 text-xs font-semibold text-slate-500"><CalendarDays className="h-3.5 w-3.5 text-emerald-600" />Reported</div><p className="text-sm font-bold text-slate-900">{createdAt.toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' })}</p><p className="text-[11px] text-slate-500">{createdAt.toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit' })}</p></div>
        <div className="rounded-xl border border-slate-200 bg-slate-50 p-3.5"><div className="mb-1 flex items-center gap-2 text-xs font-semibold text-slate-500"><Clock3 className="h-3.5 w-3.5 text-amber-600" />Estimated follow-up target</div><p className="text-sm font-bold text-slate-900">{target.toLocaleDateString('en-IN', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' })}</p>{!['RESOLVED', 'CLOSED'].includes(status) && <span className={`mt-1 inline-block rounded px-2 py-0.5 text-[10px] font-bold ${remaining.badgeClass}`}>{remaining.text}</span>}</div>
      </div>
      <p className="mt-4 text-[11px] text-slate-500">The target is an estimate generated by CityNova and is not an official city service guarantee.</p>
    </section>
  );
}
